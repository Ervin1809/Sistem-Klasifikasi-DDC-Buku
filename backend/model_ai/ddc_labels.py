def get_seksi_label(seksi: str) -> str:
    """Mengembalikan label deskriptif seksi DDC.
    
    Jika seksi tidak ditemukan langsung, mencoba mencari induk kelasnya.
    """
    clean_seksi = seksi.strip()
    if clean_seksi in SEKSI_DDC_LABELS:
        return SEKSI_DDC_LABELS[clean_seksi]

    # Cek jika kode berawalan 0xx, 1xx, dsb
    prefix = clean_seksi[:1] + "00"
    if prefix in SEKSI_DDC_LABELS:
        return SEKSI_DDC_LABELS[prefix]

    return f"Seksi DDC {clean_seksi}"

